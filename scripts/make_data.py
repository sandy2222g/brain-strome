"""Generate synthetic contacts with known duplicate groups (ground truth in `group`)."""

from __future__ import annotations

import json
import random
from pathlib import Path

FIRST = [
    "Maria",
    "James",
    "Aisha",
    "Wei",
    "Olga",
    "Carlos",
    "Priya",
    "Liam",
    "Fatima",
    "Noah",
    "Sofia",
    "Kenji",
    "Ines",
    "Tomas",
    "Zara",
]
LAST = [
    "Garcia",
    "Smith",
    "Khan",
    "Chen",
    "Ivanova",
    "Lopez",
    "Patel",
    "Murphy",
    "Hassan",
    "Meyer",
    "Rossi",
    "Tanaka",
    "Silva",
    "Novak",
    "Ali",
]
NICK = {"James": "Jim", "Maria": "Mari", "Tomas": "Tom", "Liam": "Will", "Noah": "Noe"}


def typo(s: str, rng: random.Random) -> str:
    if len(s) < 4:
        return s
    i = rng.randrange(1, len(s) - 1)
    return s[:i] + s[i + 1] + s[i] + s[i + 2 :]  # swap two letters


def make(n_people: int = 90, seed: int = 4) -> list[dict[str, str | int]]:
    rng = random.Random(seed)
    people: list[tuple[str, str]] = []
    while len(people) < n_people:
        p = (rng.choice(FIRST), rng.choice(LAST))
        if p not in people:
            people.append(p)
    rows: list[dict[str, str | int]] = []
    for g, (f, last) in enumerate(people):
        phone = "".join(rng.choice("0123456789") for _ in range(10))
        email = f"{f.lower()}.{last.lower()}{rng.randint(1, 99)}@example.com"
        base = {"name": f"{f} {last}", "phone": f"{phone[:3]}-{phone[3:6]}-{phone[6:]}", "email": email, "group": g}
        rows.append(base)
        if rng.random() < 0.45:
            kind = rng.choice(["typo", "nick", "phone", "case", "email", "moved"])
            d = dict(base)
            if kind == "typo":
                d["name"] = f"{typo(f, rng)} {last}"
            elif kind == "nick":
                d["name"] = f"{NICK.get(f, f[:3])} {last}"
            elif kind == "phone":
                d["phone"] = f"({phone[:3]}) {phone[3:6]} {phone[6:]}"
            elif kind == "case":
                d["name"] = f"{last.upper()}, {f}"
            elif kind == "moved":  # new phone and email: only the (typo'd) name links the records
                d["name"] = f"{typo(f, rng)} {last}"
                d["phone"] = "".join(rng.choice("0123456789") for _ in range(10))
                d["email"] = f"{f.lower()}{rng.randint(100, 999)}@work.example.org"
            else:
                d["email"] = email.upper()
                d["name"] = f"{f} {last[0]}."
            rows.append(d)
    for g, (f, last) in enumerate(people[:12]):  # distinct look-alikes: same surname, near-identical first name
        rows.append(
            {
                "name": f"{f[:-1]}{rng.choice('aeiou')} {last}",
                "phone": "".join(rng.choice("0123456789") for _ in range(10)),
                "email": f"{f.lower()}x{rng.randint(1, 999)}@mail.example.net",
                "group": n_people + g,
            }
        )
    rng.shuffle(rows)
    for i, r in enumerate(rows):
        r["id"] = i
    return rows


if __name__ == "__main__":
    out = Path(__file__).resolve().parents[1] / "data" / "contacts.json"
    doc = {"source": "Synthetic contacts generated by scripts/make_data.py. MIT.", "contacts": make()}
    out.write_text(json.dumps(doc, indent=1))
    print("wrote", out)
