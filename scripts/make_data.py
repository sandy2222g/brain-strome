"""Generate synthetic film ratings from hidden taste factors (so we know each person's true score)."""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

GENRES = ["Comedy", "Thriller", "Romance", "Sci-Fi", "Animation", "Drama"]
WORDS = ["Last", "Midnight", "Paper", "Golden", "Hidden", "Silent", "Northern", "Electric", "Broken", "Summer"]
NOUNS = ["Harbor", "Garden", "Signal", "Letter", "Orchard", "Engine", "Mirror", "Voyage", "Kitchen", "Station"]


def make(users: int = 40, films: int = 60, seed: int = 12) -> dict[str, object]:
    rng = np.random.default_rng(seed)
    k = len(GENRES)
    taste = rng.normal(0, 1, (users, k))
    film_genre = np.zeros((films, k))
    for f in range(films):
        film_genre[f, rng.integers(k)] = 1.0
        if rng.random() < 0.35:
            film_genre[f, rng.integers(k)] += 0.6
    quality = rng.normal(0, 0.5, films)
    true = 3.2 + 0.8 * taste @ film_genre.T + quality
    true = np.clip(true, 1, 5)
    titles = [f"{WORDS[i % 10]} {NOUNS[(i * 7 + i // 10) % 10]}" for i in range(films)]
    seen = rng.random((users, films)) < 0.28
    noisy = np.clip(np.rint(true + rng.normal(0, 0.45, true.shape)), 1, 5)
    ratings = [[int(u), int(f), int(noisy[u, f])] for u in range(users) for f in range(films) if seen[u, f]]
    return {
        "source": "Synthetic ratings generated by scripts/make_data.py from hidden genre tastes. MIT.",
        "users": [f"Viewer {i + 1}" for i in range(users)],
        "films": [{"title": titles[f], "genre": GENRES[int(np.argmax(film_genre[f]))]} for f in range(films)],
        "ratings": ratings,
        "true_ratings": [[round(float(x), 2) for x in row] for row in true],
    }


if __name__ == "__main__":
    out = Path(__file__).resolve().parents[1] / "data" / "ratings.json"
    data = make()
    out.write_text(json.dumps(data))
    print("wrote", len(data["ratings"]), "ratings")
